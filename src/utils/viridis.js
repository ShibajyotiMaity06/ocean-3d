// Re-generate full clean 256-step Viridis lookup table
export const VIRIDIS_256 = [];

(function initViridis256() {
  // Exact 256 rgb triplets for Viridis
  const rawViridisKeypoints = [
    [68, 1, 84],
    [72, 35, 120],
    [62, 73, 137],
    [49, 104, 142],
    [38, 131, 142],
    [30, 158, 137],
    [53, 183, 121],
    [109, 205, 89],
    [180, 222, 44],
    [253, 231, 37]
  ];

  for (let i = 0; i < 256; i++) {
    const t = i / 255;
    const scaled = t * (rawViridisKeypoints.length - 1);
    const idx = Math.floor(scaled);
    const frac = scaled - idx;
    const nextIdx = Math.min(idx + 1, rawViridisKeypoints.length - 1);

    const c1 = rawViridisKeypoints[idx];
    const c2 = rawViridisKeypoints[nextIdx];

    const r = (c1[0] + (c2[0] - c1[0]) * frac) / 255;
    const g = (c1[1] + (c2[1] - c1[1]) * frac) / 255;
    const b = (c1[2] + (c2[2] - c1[2]) * frac) / 255;

    VIRIDIS_256.push([r, g, b]);
  }
})();

/**
 * Maps a normalized value in [0, 1] to RGB components
 * @param {number} t - Normalized value between 0.0 and 1.0
 * @returns {{r: number, g: number, b: number}}
 */
export function getViridisColor(t) {
  const clamped = Math.max(0, Math.min(1, t));
  const index = Math.min(255, Math.floor(clamped * 255));
  const rgb = VIRIDIS_256[index];
  return { r: rgb[0], g: rgb[1], b: rgb[2] };
}

/**
 * Helper to generate CSS gradient string for colorbar
 */
export function getViridisCssGradient() {
  const stops = [
    'rgb(68, 1, 84)',
    'rgb(72, 35, 120)',
    'rgb(62, 73, 137)',
    'rgb(49, 104, 142)',
    'rgb(38, 131, 142)',
    'rgb(30, 158, 137)',
    'rgb(53, 183, 121)',
    'rgb(109, 205, 89)',
    'rgb(180, 222, 44)',
    'rgb(253, 231, 37)'
  ];
  return `linear-gradient(to top, ${stops.join(', ')})`;
}
